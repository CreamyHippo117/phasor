"""Abstract algebra numerics (SPEC "Domain modules: algebra"): small finite groups, exactly.

Groups are tables of integers: elements are ``0 .. n-1`` with ``0`` the identity, and
``table[a][b]`` is the product ``a * b`` (do ``b``, then ``a``... see ``Group.compose``).
``dihedral(n)`` is the symmetries of a regular n-gon: elements ``r^k`` (rotate by 2 pi k / n)
and ``s r^k`` (a reflection), numbered ``k`` and ``n + k``. ``cyclic(n)`` is the clock Z_n,
``symmetric(n)`` all permutations of n things.
"""

from __future__ import annotations

import itertools
import math
from dataclasses import dataclass

import numpy as np


@dataclass(frozen=True)
class Group:
    name: str
    table: tuple[tuple[int, ...], ...]  # table[a][b] = a * b
    labels: tuple[str, ...]

    @property
    def order(self) -> int:
        return len(self.table)

    def mul(self, a: int, b: int) -> int:
        return self.table[a][b]

    def inverse(self, a: int) -> int:
        return next(b for b in range(self.order) if self.table[a][b] == 0)

    def element_order(self, a: int) -> int:
        x, k = a, 1
        while x != 0:
            x, k = self.table[x][a], k + 1
        return k

    def is_abelian(self) -> bool:
        return all(
            self.table[a][b] == self.table[b][a]
            for a in range(self.order)
            for b in range(self.order)
        )

    def generated(self, gens) -> frozenset[int]:
        """The subgroup generated by ``gens``."""
        seen = {0}
        frontier = [0]
        gens = list(gens)
        while frontier:
            x = frontier.pop()
            for g in gens:
                y = self.table[x][g]
                if y not in seen:
                    seen.add(y)
                    frontier.append(y)
        return frozenset(seen)

    def subgroups(self) -> list[frozenset[int]]:
        """Every subgroup (found from sets of up to two generators, which is every subgroup
        of the small groups here), smallest first."""
        found = {self.generated([])}
        for a in range(self.order):
            found.add(self.generated([a]))
        for a, b in itertools.combinations(range(self.order), 2):
            found.add(self.generated([a, b]))
        for a, b, c in itertools.combinations(range(self.order), 3):
            if self.order <= 12:
                found.add(self.generated([a, b, c]))
        return sorted(found, key=lambda s: (len(s), sorted(s)))

    def left_cosets(self, subgroup) -> list[frozenset[int]]:
        """The cosets g H of a subgroup H: they partition the group."""
        seen: set[int] = set()
        out = []
        for g in range(self.order):
            if g in seen:
                continue
            coset = frozenset(self.table[g][h] for h in subgroup)
            seen |= coset
            out.append(coset)
        return out

    def is_normal(self, subgroup) -> bool:
        return all(
            frozenset(self.table[self.table[g][h]][self.inverse(g)] for h in subgroup)
            == frozenset(subgroup)
            for g in range(self.order)
        )

    def verify(self) -> None:
        """Raise ``ValueError`` unless this is a group (identity, inverses, associativity)."""
        n = self.order
        t = np.array(self.table)
        if not all(t[0, a] == a and t[a, 0] == a for a in range(n)):
            raise ValueError("0 is not the identity")
        if not all((t[a] == 0).any() for a in range(n)):
            raise ValueError("some element has no inverse")
        if not (
            t[t[:, :, None], np.arange(n)[None, None, :]]
            == t[np.arange(n)[:, None, None], t[None, :, :]]
        ).all():
            raise ValueError("the product is not associative")


def cyclic(n: int) -> Group:
    if n < 1:
        raise ValueError("a cyclic group needs n >= 1")
    table = tuple(tuple((a + b) % n for b in range(n)) for a in range(n))
    return Group(f"Z{n}", table, tuple(str(k) for k in range(n)))


def dihedral(n: int) -> Group:
    """Symmetries of a regular n-gon (order 2n). Element k < n is the rotation r^k by
    2 pi k / n; element n + k is the reflection s r^k (first rotate by k, then flip the
    polygon over the vertical axis). ``r s = s r^-1``."""
    if n < 3:
        raise ValueError("a polygon needs n >= 3")
    size = 2 * n

    def mul(a: int, b: int) -> int:
        ra, fa = a % n, a >= n  # a = s^fa r^ra
        rb, fb = b % n, b >= n
        # s^fa r^ra s^fb r^rb = s^(fa+fb) r^(rb + (-1)^fb ra)
        r = (rb + (ra if not fb else -ra)) % n
        return n * ((fa + fb) % 2) + r

    table = tuple(tuple(mul(a, b) for b in range(size)) for a in range(size))
    labels = tuple("e" if k == 0 else (f"r{k}" if k > 1 else "r") for k in range(n)) + tuple(
        "s" if k == 0 else ("sr" if k == 1 else f"sr{k}") for k in range(n)
    )
    return Group(f"D{n}", table, labels)


def symmetric(n: int) -> Group:
    if not 1 <= n <= 5:
        raise ValueError("symmetric(n) supports n from 1 to 5 here")
    perms = list(itertools.permutations(range(n)))  # perms[0] is the identity
    index = {p: i for i, p in enumerate(perms)}
    table = tuple(tuple(index[tuple(a[b[i]] for i in range(n))] for b in perms) for a in perms)
    return Group(f"S{n}", table, tuple("".join(str(x + 1) for x in p) for p in perms))


def polygon_action(n: int, element: int) -> tuple[float, bool]:
    """How a dihedral element moves the polygon: (rotation angle in radians, flipped)."""
    return (2 * math.pi * (element % n) / n, element >= n)


def action_matrix(n: int, element: int) -> np.ndarray:
    """The 2x2 matrix of a dihedral element (rotate by k, then mirror over the y axis when it
    is a reflection): the group acting on the plane."""
    ang, flip = polygon_action(n, element)
    rot = np.array([[math.cos(ang), -math.sin(ang)], [math.sin(ang), math.cos(ang)]])
    return np.array([[-1.0, 0.0], [0.0, 1.0]]) @ rot if flip else rot
